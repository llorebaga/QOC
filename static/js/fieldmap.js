/* QOC — interactive field map (D3 force layout).
   Data: <script id="fm-data"> with {families, nodes, links} generated by build.py. */
(function () {
  "use strict";
  const root = document.querySelector("[data-fieldmap]");
  const dataEl = document.getElementById("fm-data");
  if (!root || !dataEl || typeof window.d3 === "undefined") return;

  const d3 = window.d3;
  const data = JSON.parse(dataEl.textContent);
  const canvas = root.querySelector("[data-fm-canvas]");
  const card = root.querySelector("[data-fm-card]");
  const search = root.querySelector("[data-fm-search]");
  const famButtons = Array.from(root.querySelectorAll(".fm-fam"));
  const famIndex = new Map(data.families.map((f, i) => [f.id, i]));
  const byId = new Map(data.nodes.map((n) => [n.id, n]));
  const neighbours = new Map(data.nodes.map((n) => [n.id, new Set()]));
  data.links.forEach((l) => { neighbours.get(l.source).add(l.target); neighbours.get(l.target).add(l.source); });

  let svg, zoomLayer, nodeSel, linkSel, labelSel, famLabelSel, zoom, sim;
  let pinned = null;            // node shown in the card after a tap/focus
  let familyFocus = null;       // family highlighted from the legend
  let query = "";
  let layoutKind = null;

  /* ---------------------------------------------------------------- layout */
  function dims() {
    const narrow = canvas.clientWidth < 640;
    // On phones the graph keeps a readable natural size and the frame scrolls horizontally.
    return narrow ? { w: 760, h: 1000, rx: 250, ry: 370, kind: "narrow", font: 13 }
                  : { w: 1160, h: 780, rx: 430, ry: 270, kind: "wide", font: 12.5 };
  }

  function build() {
    const D = dims();
    layoutKind = D.kind;
    canvas.innerHTML = "";
    const F = data.families.length;
    const anchor = (fid) => {
      const a = -Math.PI / 2 + (2 * Math.PI * famIndex.get(fid)) / F;
      return [D.w / 2 + D.rx * Math.cos(a), D.h / 2 + D.ry * Math.sin(a)];
    };

    const nodes = data.nodes.map((n, i) => {
      const [ax, ay] = anchor(n.family);
      const k = data.nodes.filter((m) => m.family === n.family).indexOf(n);
      const labelW = n.label.length * D.font * 0.56;      // rough text width
      return { ...n, r: 6 + 1.6 * Math.sqrt(n.degree), labelW,
               x: ax + 18 * Math.cos(k * 2.4), y: ay + 18 * Math.sin(k * 2.4), ax, ay };
    });
    const nodeById = new Map(nodes.map((n) => [n.id, n]));
    const links = data.links.map((l) => ({ source: nodeById.get(l.source), target: nodeById.get(l.target) }));

    // Family names take part in the layout as label-sized bodies placed outside their cluster,
    // so topics move out of their way and nothing overlaps.
    const famFont = D.font * 0.9;
    const labels = data.families.map((f) => {
      const [ax, ay] = anchor(f.id);
      const dx = ax - D.w / 2, dy = ay - D.h / 2, len = Math.hypot(dx, dy) || 1;
      const out = D.kind === "wide" ? 110 : 90;
      const labelW = f.title.length * famFont * 0.68 + 10;
      return { ...f, isFamily: true, labelW, r: 8,
               ax: ax + (dx / len) * out, ay: ay + (dy / len) * out * 0.75, x: ax + (dx / len) * out, y: ay + (dy / len) * out };
    });
    const bodies = nodes.concat(labels);
    const clampX = (d) => Math.max(d.labelW / 2 + 8, Math.min(D.w - d.labelW / 2 - 8, d.x));
    const clampY = (d) => Math.max(d.isFamily ? 18 : 40, Math.min(D.h - (d.isFamily ? 40 : 44), d.y));

    sim = d3.forceSimulation(bodies)
      .force("link", d3.forceLink(links).distance(90).strength(0.015))
      .force("charge", d3.forceManyBody().strength((d) => (d.isFamily ? 0 : -120)).distanceMax(260))
      .force("x", d3.forceX((d) => d.ax).strength((d) => (d.isFamily ? 0.5 : 0.3)))
      .force("y", d3.forceY((d) => d.ay).strength((d) => (d.isFamily ? 0.5 : 0.3)))
      // label-aware collision: labels sit under nodes, so their half-width dominates
      .force("collide", d3.forceCollide((d) => (d.isFamily ? d.labelW / 2 : Math.max(d.r + 12, d.labelW / 2 + 6)))
        .strength(0.9).iterations(3))
      .force("bounds", () => bodies.forEach((d) => { d.x = clampX(d); d.y = clampY(d); }))
      .stop();
    for (let i = 0; i < 480; i++) sim.tick();
    bodies.forEach((d) => { d.x = clampX(d); d.y = clampY(d); });   // final positions strictly inside the frame
    labels.forEach((d) => { d.fx = d.x; d.fy = d.y; });   // family names stay put when topics are dragged

    svg = d3.select(canvas).append("svg")
      .attr("viewBox", `0 0 ${D.w} ${D.h}`)
      .style("width", D.kind === "narrow" ? D.w + "px" : null)
      .attr("role", "group")
      .attr("aria-label", "Field map: topics of quantum optimal control and their connections");
    zoomLayer = svg.append("g");

    linkSel = zoomLayer.append("g").attr("class", "fm-links").selectAll("line").data(links).join("line");

    famLabelSel = zoomLayer.append("g").attr("class", "fm-famlabels").selectAll("text").data(labels).join("text")
      .attr("x", (d) => d.x)
      .attr("y", (d) => d.y + famFont * 0.35)
      .attr("text-anchor", "middle")
      .style("font-size", famFont + "px")
      .style("fill", (d) => `var(--fam-${d.id})`)
      .text((d) => d.title);

    const g = zoomLayer.append("g").attr("class", "fm-nodes").selectAll("a").data(nodes).join("a")
      .attr("href", (d) => d.url)
      .attr("class", (d) => "fm-node" + (d.article ? " has-article" : ""))
      .attr("aria-label", (d) => `${d.title} (${data.families[famIndex.get(d.family)].title})`)
      .style("--fam", (d) => `var(--fam-${d.family})`);
    g.append("circle").attr("r", (d) => d.r);
    g.append("text").attr("class", "fm-label").attr("dy", (d) => d.r + D.font + 1).attr("text-anchor", "middle").text((d) => d.label);
    nodeSel = g;
    labelSel = g.select("text");

    positions();

    // interaction
    g.on("mouseenter", (e, d) => show(d))
     .on("mouseleave", () => { if (!pinned) show(null); })
     .on("focus", (e, d) => { pinned = d; show(d); })
     .on("blur", () => { pinned = null; show(null); })
     .on("click", (e, d) => {
       // touch: first tap shows the card, second tap follows the link
       if (e.pointerType === "touch" || (e.sourceCapabilities && e.sourceCapabilities.firesTouchEvents)) {
         if (pinned !== d) { e.preventDefault(); pinned = d; show(d); }
       }
     });

    g.call(d3.drag()
      .on("start", (e, d) => { if (!e.active) sim.alphaTarget(0.15).restart(); d.fx = d.x; d.fy = d.y; })
      .on("drag", (e, d) => { d.fx = e.x; d.fy = e.y; })
      .on("end", (e, d) => { if (!e.active) sim.alphaTarget(0); d.fx = null; d.fy = null; }));
    sim.on("tick", positions);

    zoom = d3.zoom().scaleExtent([0.6, 4])
      .filter((e) => (e.type === "wheel" ? e.ctrlKey || e.metaKey : !e.button) && !(e.touches && e.touches.length < 2))
      .on("zoom", (e) => { zoomLayer.attr("transform", e.transform); placeCard(); });
    svg.call(zoom).on("dblclick.zoom", null);
    svg.on("click", (e) => { if (e.target === svg.node()) { pinned = null; show(null); } });

    applyHighlight();
    if (D.kind === "narrow") canvas.scrollLeft = (D.w - canvas.clientWidth) / 2;   // start centred
  }

  function positions() {
    linkSel.attr("x1", (d) => d.source.x).attr("y1", (d) => d.source.y)
           .attr("x2", (d) => d.target.x).attr("y2", (d) => d.target.y);
    nodeSel.attr("transform", (d) => `translate(${d.x},${d.y})`);
    placeCard();
  }

  /* ---------------------------------------------------------------- highlight */
  let hovered = null;
  function show(d) {
    hovered = d;
    applyHighlight();
    if (!d) { card.hidden = true; return; }
    const fam = data.families[famIndex.get(d.family)];
    card.innerHTML = "";
    card.style.setProperty("--fam", `var(--fam-${d.family})`);
    const f = document.createElement("p"); f.className = "fm-card-fam"; f.textContent = fam.title;
    const t = document.createElement("p"); t.className = "fm-card-title"; t.textContent = d.title;
    const s = document.createElement("p"); s.className = "fm-card-short"; s.textContent = d.short;
    const a = document.createElement("a"); a.href = d.url; a.className = "fm-card-link";
    a.textContent = d.article ? "Read the article →" : "Open topic page →";
    card.append(f, t, s, a);
    card.hidden = false;
    placeCard();
  }

  function placeCard() {
    if (!hovered || card.hidden || !svg) return;
    const node = nodeSel.filter((n) => n.id === hovered.id).node();
    if (!node) return;
    const nb = node.getBoundingClientRect(), cb = canvas.getBoundingClientRect();
    const cw = card.offsetWidth, ch = card.offsetHeight;
    let x = nb.left - cb.left + nb.width / 2 + 16;
    let y = nb.top - cb.top - 8;
    if (x + cw > cb.width - 8) x = nb.left - cb.left + nb.width / 2 - cw - 16;
    x = Math.max(8, x);
    y = Math.max(8, Math.min(cb.height - ch - 8, y));
    card.style.transform = `translate(${x}px, ${y}px)`;
  }

  function matches(n) {
    if (!query) return true;
    const hay = (n.title + " " + n.label + " " + n.aliases.join(" ") + " " + n.short).toLowerCase();
    return query.split(/\s+/).every((w) => hay.includes(w));
  }

  function applyHighlight() {
    if (!nodeSel) return;
    const focus = hovered ? new Set([hovered.id, ...neighbours.get(hovered.id)]) : null;
    nodeSel.classed("is-dim", (n) => {
      if (focus) return !focus.has(n.id);
      if (familyFocus && n.family !== familyFocus) return true;
      return !matches(n);
    }).classed("is-active", (n) => hovered && n.id === hovered.id)
      .classed("is-match", (n) => !!query && matches(n));
    linkSel.classed("is-hot", (l) => hovered && (l.source.id === hovered.id || l.target.id === hovered.id))
           .classed("is-dim", (l) => (hovered && !(l.source.id === hovered.id || l.target.id === hovered.id)) ||
                                     (!hovered && (!!query || !!familyFocus)));
    famLabelSel.classed("is-dim", (f) => familyFocus && f.id !== familyFocus);
  }

  /* ---------------------------------------------------------------- outline filtering */
  const cards = Array.from(document.querySelectorAll("[data-fm-topic]"));
  const blocks = Array.from(document.querySelectorAll("[data-fm-family]"));
  const empty = document.querySelector("[data-fm-empty]");
  function filterOutline() {
    let shown = 0;
    cards.forEach((c) => {
      const ok = (!query || query.split(/\s+/).every((w) => c.dataset.search.includes(w))) &&
                 (!familyFocus || byId.get(c.dataset.fmTopic).family === familyFocus);
      c.hidden = !ok; if (ok) shown++;
    });
    blocks.forEach((b) => { b.hidden = !b.querySelector("[data-fm-topic]:not([hidden])"); });
    if (empty) empty.hidden = shown > 0;
  }

  search.addEventListener("input", () => { query = search.value.trim().toLowerCase(); applyHighlight(); filterOutline(); });
  search.addEventListener("keydown", (e) => {
    if (e.key === "Enter") {
      const first = data.nodes.find(matches);
      if (first && query) window.location.href = first.url;
    }
  });

  famButtons.forEach((b) => b.addEventListener("click", () => {
    familyFocus = familyFocus === b.dataset.family ? null : b.dataset.family;
    famButtons.forEach((x) => x.setAttribute("aria-pressed", String(x.dataset.family === familyFocus)));
    applyHighlight(); filterOutline();
  }));

  root.querySelectorAll("[data-fm-zoom]").forEach((b) => b.addEventListener("click", () => {
    const k = b.dataset.fmZoom;
    if (k === "reset") svg.transition().duration(300).call(zoom.transform, d3.zoomIdentity);
    else svg.transition().duration(200).call(zoom.scaleBy, k === "in" ? 1.35 : 1 / 1.35);
  }));

  document.addEventListener("keydown", (e) => {
    if (e.key === "/" && document.activeElement !== search && !e.metaKey && !e.ctrlKey) { e.preventDefault(); search.focus(); }
  });

  let resizeTimer;
  window.addEventListener("resize", () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => { if (dims().kind !== layoutKind) build(); placeCard(); }, 150);
  });

  build();
})();
